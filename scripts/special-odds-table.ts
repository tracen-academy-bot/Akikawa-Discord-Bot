/**
 * Prints the special-odds tables (markdown) from the live constants, so the
 * docs never drift from the code:
 *
 *   npx ts-node --project tsconfig.scripts.json scripts/special-odds-table.ts > docs/special-sets/odds.md
 *
 * Read-only: it imports the constants and does arithmetic, nothing else.
 */
import { EARLY_START, RARE_OPENER_CHANCE, SEASONAL_BUFFS, SPECIAL_HARD_CAP, SPECIAL_SETS, SPECIAL_SOFT_CAPS, effectiveChance } from '../src/lib/timer/openers';

/** 0.105 -> "10.5%". */
const pct = (x: number) => `${Math.round(x * 1000) / 10}%`;

const base = RARE_OPENER_CHANCE;
const early = EARLY_START.chance;
const sensations = SPECIAL_SETS.find((s) => s.id === 'online-sensations')!;
const unlock = sensations.unlockBonus ?? 0;
const setBoost = sensations.openers.find((o) => o.boost)?.boost?.chance ?? 0;
const week = SEASONAL_BUFFS[0]?.chance ?? 0;

const situations: [string, number][] = [
    ['Base only', base],
    ['+ early start', base + early],
    ['Not unlocked, Curren Chan week', base + week],
    ['Not unlocked, Curren Chan week + early start', base + week + early],
    ['Unlocked (#OnlineSensations bonus)', base + unlock],
    ['Unlocked + early start', base + unlock + early],
    ['Unlocked + Loves/#ChuChuChallenge boost', base + unlock + setBoost],
    ['Unlocked + boost + early start (most today)', base + unlock + setBoost + early],
];

const out: string[] = [
    '# Special odds',
    '',
    'Generated by `scripts/special-odds-table.ts` from the constants in `src/lib/timer/openers.ts`. Do not edit by hand.',
    '',
    `Base special chance: **${pct(base)}** a ping. Boosts add to it; the total then goes through the soft caps.`,
    '',
    '## Soft caps',
    '',
    `Up to ${pct(SPECIAL_SOFT_CAPS[0]!.from)} counts in full. ` +
        SPECIAL_SOFT_CAPS.map((c) => `Raw chance above ${pct(c.from)} counts at ${c.rate === 0.5 ? 'half' : c.rate === 0.25 ? 'a quarter' : c.rate}.`).join(' ') +
        ` The effective chance never passes ${pct(SPECIAL_HARD_CAP)}. The base slice is never cut; the boosts shrink in proportion.`,
    '',
    '| Raw total | Effective |',
    '| --- | --- |',
    ...[0.1, 0.2, 0.25, 0.3, 0.35, 0.4, 0.5, 0.6].map((t) => `| ${pct(t)} | ${pct(effectiveChance(t))} |`),
    '',
    '## What a trainer gets today',
    '',
    '| Situation | Raw | Effective |',
    '| --- | --- | --- |',
    ...situations.map(([name, t]) => `| ${name} | ${pct(t)} | ${pct(effectiveChance(t))} |`),
    '',
];
process.stdout.write(out.join('\n'));
